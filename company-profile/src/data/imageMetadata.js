/**
 * Mengambil metadata gambar berdasarkan nama file dan bahasa
 */
export function getImageMetadata(fileName, lang = "id") {
  if (!fileName) return null;
  const cleanName = fileName.replace(/^\//, "");
  const meta = IMAGE_METADATA[cleanName];
  if (!meta) {
    return {
      alt: cleanName.replace(/\.[^/.]+$/, "").replace(/[-_]/g, " "),
      description: "Aset visual PT Penilai Standar Uji",
      width: 800,
      height: 600,
      format: "image/webp",
      is_decorative: false
    };
  }
  return {
    alt: lang === "en" ? meta.alt_en : meta.alt_id,
    description: lang === "en" ? meta.desc_en : meta.desc_id,
    width: meta.width,
    height: meta.height,
    format: meta.format,
    is_decorative: meta.is_decorative
  };
}

/**
 * Menghasilkan objek ImageObject Schema valid untuk JSON-LD
 */
export function buildImageObjectSchema(fileName, customCaption = null, baseUrl = BASE_SITE_URL) {
  if (!fileName) return null;
  const cleanName = fileName.replace(/^\//, "");
  const meta = IMAGE_METADATA[cleanName];
  const url = `${baseUrl}/${encodeURIComponent(cleanName).replace(/%2F/g, "/")}`;
  
  return {
    "@type": "ImageObject",
    "@id": `${url}#image`,
    url: url,
    contentUrl: url,
    name: meta?.alt_id || cleanName,
    caption: customCaption || meta?.desc_id || meta?.alt_id || cleanName,
    description: meta?.desc_id || meta?.alt_id || cleanName,
    width: meta?.width || 1200,
    height: meta?.height || 800,
    encodingFormat: meta?.format || "image/webp"
  };
}

